// Это файл-чертеж. Он объясняет приложению, как устроено любое достижение в игре.
class Achievement {
  // Уникальный ID достижения (например, "tasks_done"). 
  // Нужен программе, чтобы не путать разные достижения между собой.
  final String id;

  // Красивое название достижения, которое видит игрок на экране (например, "Задачник").
  final String title;

  // Список названий для каждого уровня (например: ["Новичок", "Мастер", "Легенда"]).
  final List<String> levelTitles; 

  // Список чисел-целей, которые нужно набрать для перехода на следующий уровень (например: [10, 50, 100]).
  final List<int> thresholds;    

  // Текущий прогресс игрока (сколько уже сделано, например, выполнено задач). 
  // Эта цифра будет расти по ходу игры, поэтому здесь нет слова "final".
  int currentProgress; 

  // Какой сейчас открыт уровень (0 — еще ничего не получено, 1 — открыт первый уровень и т.д.).
  int currentLevel;    

  // Это инструкция (конструктор), которая создает конкретное достижение в памяти телефона.
  Achievement({
    required this.id,             // Без ID создать достижение нельзя (оно обязательное)
    required this.title,          // Название тоже обязательное
    required this.levelTitles,    // Список названий уровней обязателен
    required this.thresholds,     // Список целей-пороков обязателен
    this.currentProgress = 0,     // Если при создании число не передали, по умолчанию ставим 0
    this.currentLevel = 0,        // И уровень тоже по умолчанию начинаем с 0
  });
}